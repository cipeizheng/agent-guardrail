"""Third-party release-axis cases for the detection benchmark.

Sources (see preregistration.md): BIPIA attack payloads (attack), NotInject
(benign hard negatives), and the AgentDojo injection export (attack). The
BIPIA/NotInject files are SHA-256 verified against the manifest that
evals/prompt_injection/fetch.py pinned; the AgentDojo export is generated by
gen_agentdojo.py from a version-recorded install. Texts are never rewritten,
only wrapped in a fixed tool-result envelope.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from corpus import Case, FactProbe, PriorStep

_HERE = Path(__file__).resolve().parent
_ROOT = _HERE.parents[1]
_PROMPT_INJECTION_DIR = _ROOT / "evals" / "prompt_injection"
_DATA_DIR = _ROOT / "data" / "benchmarks" / "prompt-injection"
_AGENTDOJO_EXPORT = _ROOT / "data" / "benchmarks" / "detection" / "agentdojo-release.json"
_AGENTDOJO_FLOW = _ROOT / "data" / "benchmarks" / "detection" / "agentdojo-flow.json"

_AXIS = "release_external"
_ENVELOPE = "Document fetched from https://external.example/article:\n\n{}\n\n-- end of document --"


def _short_id(source: str, material: str) -> str:
    digest = hashlib.sha256(material.encode()).hexdigest()[:12]
    return f"ext-{source}-{digest}"


def _case(source: str, case_id: str, payload: str, attack: bool, note: str) -> Case:
    output = _ENVELOPE.format(payload)
    return Case(
        case_id=case_id,
        axis=_AXIS,
        label="block" if attack else "allow",
        goal="Summarize the fetched document.",
        pending_tool="send_email",
        pending_arguments={"to": "me@example.com", "subject": "Summary", "body": "See attached."},
        prior=(
            PriorStep(
                tool="fetch_url",
                arguments={"url": "https://external.example/article"},
                output=output,
            ),
        ),
        rationale=note,
        decision_point="tool_result_release",
        fact_probes=(FactProbe(capability="prompt_injection", text=output, expect_fact=attack),),
    )


def _verified_manifest_files() -> list[tuple[str, str, Path]]:
    """Return (benchmark_id, path, absolute file) for every manifest entry."""

    manifest = json.loads(
        (_PROMPT_INJECTION_DIR / "manifest.json").read_text(encoding="utf-8")
    )
    files = []
    for benchmark in manifest["benchmarks"]:
        for entry in benchmark["files"]:
            path = _DATA_DIR / entry["path"]
            if not path.is_file():
                raise FileNotFoundError(
                    f"corpus file missing; run evals/prompt_injection/fetch.py: {path}"
                )
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            if digest != entry["sha256"]:
                raise RuntimeError(f"corpus file hash mismatch: {path}")
            files.append((benchmark["id"], entry["path"], path))
    return files


def _bipia_notinject_cases() -> list[Case]:
    cases = []
    for benchmark_id, _rel, path in _verified_manifest_files():
        raw = json.loads(path.read_text(encoding="utf-8"))
        if benchmark_id == "notinject":
            samples = [(item["category"], item["prompt"]) for item in raw]
            attack = False
        elif benchmark_id == "bipia":
            samples = [(category, text) for category, texts in raw.items() for text in texts]
            attack = True
        else:
            continue
        for category, text in samples:
            case_id = _short_id(benchmark_id, f"{path.name}\0{category}\0{text}")
            cases.append(
                _case(
                    benchmark_id,
                    case_id,
                    text,
                    attack,
                    f"{benchmark_id}/{path.name}/{category}",
                )
            )
    return cases


def _agentdojo_cases() -> list[Case]:
    if not _AGENTDOJO_EXPORT.is_file():
        return []
    export = json.loads(_AGENTDOJO_EXPORT.read_text(encoding="utf-8"))
    cases = []
    for entry in export["cases"]:
        case_id = _short_id("agentdojo", f"{entry['suite']}\0{entry['task_id']}")
        cases.append(
            _case(
                "agentdojo",
                case_id,
                entry["attack_text"],
                attack=True,
                note=(
                    f"agentdojo/{export['agentdojo_version']}/"
                    f"{entry['suite']}/{entry['task_id']}"
                ),
            )
        )
    return cases


def _agentdojo_flow_cases() -> list[Case]:
    """Field-level flow cases from the AgentDojo export (see preregistration.md).

    Attack: the injection's prescribed malicious sink call, with the attack
    text sitting in one untrusted read output; the user goal is an unrelated
    benign prompt. Benign: the user task's own sink call; the read output
    carries the destination value (worst case for the delegated group).
    """

    if not _AGENTDOJO_FLOW.is_file():
        return []
    export = json.loads(_AGENTDOJO_FLOW.read_text(encoding="utf-8"))
    read_tools = export["read_tools"]
    version = export["agentdojo_version"]
    cases = []
    for entry in export["attack_cases"]:
        tool, arguments = read_tools[entry["suite"]]
        sink = entry["sink_call"]
        cases.append(
            Case(
                case_id=_short_id("ajatk", f"{entry['suite']}\0{entry['task_id']}"),
                axis="flow_agentdojo",
                label="block",
                goal=entry["user_prompt"],
                pending_tool=sink["function"],
                pending_arguments=dict(sink["arguments"]),
                prior=(
                    PriorStep(
                        tool=tool,
                        arguments=dict(arguments),
                        output=entry["attack_text"],
                    ),
                ),
                rationale=(
                    f"agentdojo-attack/{version}/{entry['suite']}/{entry['task_id']}"
                ),
            )
        )
    for entry in export["benign_cases"]:
        tool, arguments = read_tools[entry["suite"]]
        sink = entry["sink_call"]
        group = "named" if entry["named"] else "delegated"
        output = (
            "Here is the information you asked for:\n\n"
            f"{sink['dest_value']}\n\n(end of output)"
        )
        cases.append(
            Case(
                case_id=_short_id("ajben", f"{entry['suite']}\0{entry['task_id']}"),
                axis="flow_agentdojo",
                label="allow",
                goal=entry["prompt"],
                pending_tool=sink["function"],
                pending_arguments=dict(sink["arguments"]),
                prior=(
                    PriorStep(
                        tool=tool,
                        arguments=dict(arguments),
                        output=output,
                    ),
                ),
                rationale=(
                    f"agentdojo-benign-{group}/{version}/{entry['suite']}/{entry['task_id']}"
                ),
            )
        )
    return cases


def load_external_cases() -> tuple[Case, ...]:
    """Build all available external cases; empty when the data has not been fetched."""

    if not _DATA_DIR.is_dir():
        return ()
    cases = _bipia_notinject_cases() + _agentdojo_cases() + _agentdojo_flow_cases()
    seen = {case.case_id for case in cases}
    if len(seen) != len(cases):
        raise RuntimeError("external case IDs are not unique")
    return tuple(cases)
